# PowerShell script to clean trailing whitespace and ensure exactly one trailing newline at the end of
# source, config, and documentation files.
#
# Preserves each file's existing line-ending style (CRLF or LF) and skips any file carrying a
# generated-code header.
#
# The filter lists below are the single source of truth for what this script touches. They are
# duplicated in prose in scripts/AGENTS.md, so update both together.
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# --- Filter lists ---------------------------------------------------------------
# Matched against FileInfo.Extension, case-insensitively.
$extensions = @('.cs', '.ts', '.tsx', '.sql', '.md', '.json', '.yml', '.yaml', '.css', '.razor', '.ps1')

# Matched against FileInfo.Name. Covers extensionless files that still need cleaning: a trailing
# space in .gitignore becomes part of the pattern and silently breaks the ignore rule.
$filenames = @('Dockerfile', '.gitignore', '.dockerignore', '.env.example', 'AGENTS.md')

# Matched with -like, so wildcards work.
$filenamePatterns = @('Directory.*.props', '*.slnx')

# Directory segments to skip entirely.
$excludedDirectories = @('\bin\', '\obj\', '\node_modules\', '\generated\', '\.git\', '\.vs\', '\.vscode\', '\artifacts\', '\TestResults\')
# --------------------------------------------------------------------------------

# Always resolve the repository root relative to this script's location (scripts/tools -> repo root)
$solutionRoot = Resolve-Path (Join-Path $PSScriptRoot '../..')

function Test-ShouldClean {
    param([System.IO.FileInfo]$File)

    foreach ($segment in $excludedDirectories) {
        if ($File.FullName -like "*$segment*") { return $false }
    }

    if ($File.Extension -and $extensions -contains $File.Extension.ToLowerInvariant()) { return $true }
    if ($filenames -contains $File.Name) { return $true }

    foreach ($pattern in $filenamePatterns) {
        if ($File.Name -like $pattern) { return $true }
    }

    return $false
}

$files = @(Get-ChildItem -Path $solutionRoot -File -Recurse | Where-Object { Test-ShouldClean $_ })
Write-Host "Scanning $($files.Count) file(s) under: $solutionRoot"

$cleanedFiles = New-Object System.Collections.Generic.List[string]
$skippedGenerated = 0

foreach ($file in $files) {
    $raw = [System.IO.File]::ReadAllText($file.FullName)

    if ([string]::IsNullOrEmpty($raw)) {
        continue
    }

    # Skip generated code. The marker must appear in the header region only. Scanning the whole file
    # false-positives on documentation that merely mentions "generated by" in prose, which is how
    # AGENTS.md got caught the first time this ran.
    $header = ($raw -split "`r?`n" | Select-Object -First 5) -join "`n"
    if ($header -match '(?i)<auto-generated|^\s*(//|#|/\*)\s*generated by|^\s*(//|#)\s*Code generated by') {
        $skippedGenerated++
        continue
    }

    # Detect the file's current line ending (CRLF vs LF)
    # If we find LF without CR, we use LF; otherwise we default to CRLF (\r\n)
    $lineEnding = "`r`n"
    if ($raw -match "(?<!\r)\n") {
        $lineEnding = "`n"
    }

    # Trim all trailing whitespace and newlines, then add exactly ONE trailing newline.
    #
    # .ps1 files get EOF normalization only, never per-line trimming. Trailing whitespace inside
    # a here-string is part of that string's value, and no line-based or regex approach can
    # reliably tell a here-string delimiter from the same characters inside a quoted literal.
    # A malformed script is a far worse outcome than an untidy one, so .ps1 files are exempt
    # from line trimming and only get the final-newline guarantee.
    $trimmed = $raw.TrimEnd() + $lineEnding

    if ($raw -ne $trimmed) {
        # Preserve the original encoding. Writing UTF8 unconditionally would strip a BOM.
        $bytes = [System.IO.File]::ReadAllBytes($file.FullName)
        $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
        $encoding = if ($hasBom) { [System.Text.UTF8Encoding]::new($true) } else { [System.Text.UTF8Encoding]::new($false) }

        [System.IO.File]::WriteAllText($file.FullName, $trimmed, $encoding)
        $cleanedFiles.Add($file.FullName.Substring($solutionRoot.Path.Length + 1))
    }
}

if ($cleanedFiles.Count -gt 0) {
    Write-Host "Cleaned $($cleanedFiles.Count) file(s):" -ForegroundColor Yellow
    foreach ($path in $cleanedFiles) {
        Write-Host "  M $path" -ForegroundColor DarkYellow
    }
}
else {
    Write-Host 'Cleaned 0 files. Already tidy.' -ForegroundColor Green
}

if ($skippedGenerated -gt 0) {
    Write-Host "Skipped $skippedGenerated generated file(s)." -ForegroundColor DarkGray
}

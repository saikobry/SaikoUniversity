# PowerShell script to clean trailing whitespace and ensure exactly one trailing newline at the end of
# source, config, and documentation files.
#
# Scans .cs, .ts, .tsx, .sql, .md, .json, .yml, and .css. Skips bin/, obj/, node_modules/,
# generated/, .git/, and .vs/. Preserves each file's existing line-ending style and skips any file
# carrying a generated-code header.
$ErrorActionPreference = 'Stop'

# Always resolve the repository root relative to this script's location (scripts/tools -> repo root)
$solutionRoot = Resolve-Path (Join-Path $PSScriptRoot "../..")
Write-Host "Scanning for C# (*.cs), TypeScript (*.ts), and SQL (*.sql) files under: $solutionRoot"

$files = Get-ChildItem -Path $solutionRoot -File -Recurse | Where-Object {
    ($_.Extension -eq ".cs" -or $_.Extension -eq ".ts" -or $_.Extension -eq ".tsx" -or
     $_.Extension -eq ".sql" -or $_.Extension -eq ".md" -or $_.Extension -eq ".json" -or
     $_.Extension -eq ".yml" -or $_.Extension -eq ".css") -and
    $_.FullName -notlike "*\bin\*" -and
    $_.FullName -notlike "*\obj\*" -and
    $_.FullName -notlike "*\node_modules\*" -and
    $_.FullName -notlike "*\generated\*" -and  # Ignore Orval generated files
    $_.FullName -notlike "*\.git\*" -and
    $_.FullName -notlike "*\.vs\*"
}

$cleanedCount = 0

foreach ($file in $files) {
    # Read the raw file content
    $raw = [System.IO.File]::ReadAllText($file.FullName)

    if ([string]::IsNullOrEmpty($raw)) {
        continue
    }

    # Ignore files generated by Orval (check comment header)
    if ($raw -match "Generated by orval") {
        continue
    }

    # Detect the file's current line ending (CRLF vs LF)
    # If we find LF without CR, we use LF; otherwise we default to CRLF (\r\n)
    $lineEnding = "`r`n"
    if ($raw -match "(?<!\r)\n") {
        $lineEnding = "`n"
    }

    # Trim all trailing whitespace and newlines, then add exactly ONE trailing newline
    $trimmed = $raw.TrimEnd() + $lineEnding

    if ($raw -ne $trimmed) {
        # Keep UTF-8 encoding (or UTF-8 with BOM if the file had one)
        [System.IO.File]::WriteAllText($file.FullName, $trimmed, [System.Text.Encoding]::UTF8)
        $cleanedCount++
    }
}

Write-Host "Successfully cleaned $cleanedCount files (removed trailing whitespace/extra newlines)."